import XCTest
import Foundation
@testable import PlaybackStatus

/// The full rules table (every audio and video row) is generated from the rules code and must equal
/// the golden copy in RulesGolden.swift, row for row. docs/PLAYBACK_STATUS.md holds the same table
/// between the RULES-TABLE markers; scripts/playback-status-doc.sh checks that copy against the golden.
///
/// To accept a deliberate change: VP_UPDATE_GOLDEN=1 VP_REPO_ROOT=<repo root> swift test --filter GoldenTests
/// The test rewrites the golden file and the doc region and then FAILS on purpose; run it again to see green.
final class GoldenTests: XCTestCase {
    static let begin = "<!-- RULES-TABLE-BEGIN (generated, do not edit by hand) -->"
    static let end = "<!-- RULES-TABLE-END -->"

    private func trimmed(_ s: String) -> String { s.trimmingCharacters(in: .newlines) }

    func testGeneratedTableEqualsGoldenRowForRow() throws {
        let generated = trimmed(StatusTable.markdown())
        let env = ProcessInfo.processInfo.environment
        if env["VP_UPDATE_GOLDEN"] == "1" {
            guard let root = env["VP_REPO_ROOT"] else { XCTFail("VP_REPO_ROOT is required with VP_UPDATE_GOLDEN=1"); return }
            let golden = "// GENERATED by GoldenTests (VP_UPDATE_GOLDEN=1). Do not edit by hand: change the rules, then regenerate.\n"
                + "enum RulesGolden {\n    static let markdown = #\"\"\"\n" + generated + "\n\"\"\"#\n}\n"
            try golden.write(toFile: root + "/Packages/VideoPlayerCore/Tests/PlaybackStatusTests/RulesGolden.swift", atomically: true, encoding: .utf8)
            let docPath = root + "/docs/PLAYBACK_STATUS.md"
            let doc = try String(contentsOfFile: docPath, encoding: .utf8)
            guard let b = doc.range(of: Self.begin), let e = doc.range(of: Self.end), b.upperBound <= e.lowerBound else {
                XCTFail("docs/PLAYBACK_STATUS.md has no RULES-TABLE markers"); return
            }
            let updated = String(doc[..<b.upperBound]) + "\n\n" + generated + "\n\n" + String(doc[e.lowerBound...])
            try updated.write(toFile: docPath, atomically: true, encoding: .utf8)
            XCTFail("Golden file and docs/PLAYBACK_STATUS.md were rewritten. Run the tests again.")
            return
        }
        let expectedLines = trimmed(RulesGolden.markdown).components(separatedBy: "\n")
        let actualLines = generated.components(separatedBy: "\n")
        XCTAssertEqual(actualLines.count, expectedLines.count, "row count differs from the golden table")
        for (i, line) in actualLines.enumerated() where i < expectedLines.count {
            XCTAssertEqual(line, expectedLines[i], "table line \(i + 1) differs from the golden table")
        }
    }

    func testRowIDsAreUniqueAndSequential() {
        let a = StatusTable.audioRows().map(\.id)
        let v = StatusTable.videoRows().map(\.id)
        XCTAssertEqual(Set(a).count, a.count)
        XCTAssertEqual(Set(v).count, v.count)
        XCTAssertEqual(a.first, "A001")
        XCTAssertEqual(v.first, "V001")
        XCTAssertEqual(a.last, String(format: "A%03d", a.count))
        XCTAssertEqual(v.last, String(format: "V%03d", v.count))
    }
}
