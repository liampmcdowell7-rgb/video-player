import codecs, sys
encs = [("windows1250","cp1250"),("windows1251","cp1251"),("windows1252","cp1252"),("windows1253","cp1253"),
        ("windows1254","cp1254"),("windows1255","cp1255"),("windows1256","cp1256"),("windows1257","cp1257"),("windows1258","cp1258"),("windows874","cp874"),
        ("iso8859_1","latin-1"),("iso8859_2","iso8859-2"),("iso8859_15","iso8859-15"),
        ("cp437","cp437"),("cp850","cp850")]
out=[]
out.append("// GENERATED by scripts/gen-subtitle-encodings.py from Python's codec tables (Unicode consortium mappings).\n// Do not edit by hand. Each table maps bytes 0x80...0xFF to a Unicode scalar; bytes the code page leaves\n// undefined map to the same C1 control code point when below 0xA0 (as browsers do) and otherwise U+FFFD.\n")
out.append("enum SingleByteTables {")
for name,codec in encs:
    vals=[]
    for b in range(0x80,0x100):
        try:
            ch=bytes([b]).decode(codec); v=ord(ch)
        except Exception:
            v = b if b<0xA0 else 0xFFFD
        vals.append(v)
    out.append(f"    static let {name}: [UInt16] = [")
    for i in range(0,128,8):
        out.append("        "+", ".join(f"0x{v:04X}" for v in vals[i:i+8])+",")
    out.append("    ]")
out.append("}")
open(sys.argv[1],"w",encoding="utf-8").write("\n".join(out)+"\n")